create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  price numeric(12,2) not null default 0,
  old_price numeric(12,2) not null default 0,
  stock integer not null default 0,
  photo text,
  image text,
  tone text,
  badge text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.store_settings (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.products enable row level security;
alter table public.store_settings enable row level security;

drop policy if exists "Public can read active products" on public.products;
create policy "Public can read active products" on public.products for select using (active = true);

drop policy if exists "Authenticated admins manage products" on public.products;
create policy "Authenticated admins manage products" on public.products for all to authenticated using (true) with check (true);

drop policy if exists "Authenticated admins manage settings" on public.store_settings;
create policy "Authenticated admins manage settings" on public.store_settings for all to authenticated using (true) with check (true);

